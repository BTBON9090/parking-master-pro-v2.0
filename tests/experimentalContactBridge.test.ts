import assert from 'node:assert/strict';
import {CAR_MODELS} from '../constants';
import {CarType} from '../types';
import {experimentalContactsFromSamples,experimentalDriveEnabled} from '../utils/experimentalContactBridge';
const cc=CAR_MODELS[CarType.TRUCK];
assert(experimentalDriveEnabled(true,'?experimentalDrive=1',CarType.TRUCK,4));
assert(!experimentalDriveEnabled(false,'?experimentalDrive=1',CarType.TRUCK,4));
assert(!experimentalDriveEnabled(true,'',CarType.TRUCK,4));
assert(!experimentalDriveEnabled(true,'?experimentalDrive=1',CarType.US22,6));
assert(!experimentalDriveEnabled(true,'?experimentalDrive=1',CarType.TYPE100,12));
const samples=[{x:1,y:2,normalN:4000,grounded:true},{x:-1,y:2,normalN:3200,grounded:true},{x:1,y:-2,normalN:5000,grounded:true},{x:-1,y:-2,normalN:9000,grounded:false}];
const base={cc,samples,radii:[.4,.4,.4,.4],previous:null,speedMs:4,weather:.8,cornerBudget:1,sampleSurface:(x:number)=>x>0?1:.2};
const wheels=experimentalContactsFromSamples(base);
assert.equal(wheels[0].normalN,4000);assert.equal(wheels[1].normalN,3200);assert.equal(wheels[3].normalN,0);
assert(wheels[1].friction<wheels[0].friction*.21);assert.equal(wheels[0].omega,10);
const turning=experimentalContactsFromSamples({...base,cornerBudget:.3});assert(turning[0].friction<wheels[0].friction*.31);
const invalid=experimentalContactsFromSamples({...base,sampleSurface:()=>NaN,samples:samples.map(p=>({...p,normalN:NaN}))});
assert(invalid.every(w=>w.friction===0&&w.normalN===0));
assert.throws(()=>experimentalContactsFromSamples({...base,samples:samples.slice(0,3)}));
console.log('Experimental contact bridge PASS: gated, per-wheel surface/load, turn budget, airborne and invalid data');
