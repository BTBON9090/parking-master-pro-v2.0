import assert from 'node:assert/strict';
import fs from 'node:fs';
import * as THREE from 'three';
import {GLTFLoader} from 'three/examples/jsm/loaders/GLTFLoader.js';
import {CarType} from '../types';
import {CAR_MODELS} from '../constants';
import {MODEL_REGISTRY,normalizeModel} from '../three/modelLoader';
import {buildNativeAuthoredVehicle} from '../three/blenderVehicle';
import {createChassisState,stepChassis} from '../utils/chassisSupport';
import {suspensionForCar} from '../utils/suspension';
const bytes=fs.readFileSync('public/models/cars/fleet-type100.glb');
const gltf=await new GLTFLoader().parseAsync(bytes.buffer.slice(bytes.byteOffset,bytes.byteOffset+bytes.byteLength),'');
normalizeModel(gltf.scene,MODEL_REGISTRY.type100);
const parts=buildNativeAuthoredVehicle(gltf.scene,CAR_MODELS[CarType.TYPE100]);
assert.equal(parts.wheels.length,12);assert.equal(parts.wheelMounts.length,12);assert.equal(parts.frontWheels.length,2);
const wheels=parts.wheelMounts.map((m,i)=>({x:m.position.x,y:m.position.y,z:m.position.z,radius:Number(parts.wheels[i].userData.wheelRadius),halfWidth:Number(parts.wheels[i].userData.wheelWidth)/2,steer:0}));
const state=createChassisState();let pose:ReturnType<typeof stepChassis>|undefined;
for(let n=0;n<60;n++)pose=stepChassis(state,{wheels,spec:suspensionForCar(CarType.TYPE100),mass:42000,cgM:1.05,frontBias:.42,longG:0,latG:0,deltaLeft:0,deltaForward:0,rideHeight:0,dt:1/60,support:(i)=>i===4?1.2:0});
assert(pose);assert.equal(pose.contacts.length,12);assert.equal(pose.offsets.length,12);
assert(pose.offsets.every(Number.isFinite));assert(pose.contacts.every(c=>Number.isFinite(c.gap)));
assert(Math.abs(pose.offsets[4]-pose.offsets[5])>.15,`individual road wheels should react to a local bump: ${pose.offsets}`);
const node=parts.group.getObjectByName('WheelRoad1L-roll-pivot')!;const before=node.rotation.x;
const shoes=parts.group.getObjectByName('TrackShoesL') as THREE.InstancedMesh;assert(shoes);const beforeShoe=new THREE.Matrix4();shoes.getMatrixAt(0,beforeShoe);
parts.group.userData.updateTracks(5,0);assert(node.rotation.x>before+.9);const afterShoe=new THREE.Matrix4();shoes.getMatrixAt(0,afterShoe);assert(!beforeShoe.equals(afterShoe),'track shoe instance must move');
assert(parts.group.getObjectByName('WheelRoad1L-suspension-pivot')===parts.wheelMounts[4]);
console.log('Tracked suspension PASS: 12 contacts, independent bump, middle-wheel rolling');
